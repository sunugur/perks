/* Perks TR – client-side rendering for list, perk, compare and campaign pages.
   Data comes from assets/data.js (window.PERKS), generated by scripts/build.py. */
(function () {
  "use strict";
  var DATA = window.PERKS || { meta: {}, products: [] };
  var META = DATA.meta;
  var PRODUCTS = DATA.products;
  var BASE = document.body.getAttribute("data-base") || "";
  var TODAY = new Date().toISOString().slice(0, 10);
  var MAX_COMPARE = 4;
  var CMP_KEY = "perks-compare";

  function $(sel, root) { return (root || document).querySelector(sel); }
  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }
  function norm(s) {
    return String(s || "").toLocaleLowerCase("tr").normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/ı/g, "i");
  }
  function fmtDate(iso) {
    if (!iso) return "";
    var p = iso.split("-");
    var months = ["Ocak", "Şubat", "Mart", "Nisan", "Mayıs", "Haziran", "Temmuz", "Ağustos", "Eylül", "Ekim", "Kasım", "Aralık"];
    return parseInt(p[2], 10) + " " + months[parseInt(p[1], 10) - 1] + " " + p[0];
  }
  function activeCampaigns(p) {
    return (p.campaigns || []).filter(function (c) { return !c.until || c.until >= TODAY; });
  }
  function isFree(p) { return /^(aidatsız|ücretsiz|uygulama ücretsiz)/i.test((p.costs && p.costs.fee) || ""); }
  function byId(id) { for (var i = 0; i < PRODUCTS.length; i++) if (PRODUCTS[i].id === id) return PRODUCTS[i]; return null; }
  function url(p) { return BASE + "urun/" + p.id + ".html"; }

  /* ---------- compare selection (per-viewer convenience only) ---------- */
  function getCmp() {
    try { return JSON.parse(localStorage.getItem(CMP_KEY) || "[]").filter(byId); } catch (e) { return []; }
  }
  function setCmp(list) {
    try { localStorage.setItem(CMP_KEY, JSON.stringify(list)); } catch (e) { /* storage unavailable */ }
    renderTray();
  }
  function toggleCmp(id, on) {
    var list = getCmp().filter(function (x) { return x !== id; });
    if (on) {
      if (list.length >= MAX_COMPARE) { alert("En fazla " + MAX_COMPARE + " ürün karşılaştırabilirsiniz."); return false; }
      list.push(id);
    }
    setCmp(list);
    return true;
  }
  function renderTray() {
    var tray = $("#tray");
    if (!tray) return;
    var list = getCmp();
    tray.classList.toggle("show", list.length > 0);
    $(".sel", tray).innerHTML = list.map(function (id) { return "<span>" + esc(byId(id).name) + "</span>"; }).join("");
    var go = $("#tray-go", tray);
    go.disabled = list.length < 2;
    go.onclick = function () { location.href = BASE + "karsilastir.html?ids=" + list.join(","); };
    $("#tray-clear", tray).onclick = function () {
      setCmp([]);
      document.querySelectorAll("input[data-cmp]").forEach(function (cb) { cb.checked = false; });
    };
  }

  /* ---------- product card ---------- */
  function card(p) {
    var cat = META.categories[p.category] || {};
    var camps = activeCampaigns(p);
    var badges = "";
    if (p.status !== "aktif") badges += '<span class="badge ' + p.status + '">' + esc(META.status[p.status]) + "</span>";
    if (camps.length) badges += '<span class="badge kampanya">' + camps.length + " kampanya</span>";
    var checked = getCmp().indexOf(p.id) >= 0 ? " checked" : "";
    return '<article class="card' + (p.status === "kapandi" ? " closed" : "") + '">' +
      '<div class="card-top"><div><h3><a href="' + url(p) + '">' + esc(p.name) + "</a></h3>" +
      '<div class="prov">' + esc(cat.icon || "") + " " + esc(p.provider) + " · " + esc(p.subcategory) + "</div></div>" +
      "<div>" + badges + "</div></div>" +
      '<p class="sum">' + esc(p.summary) + "</p>" +
      "<ul>" + p.benefits.slice(0, 3).map(function (b) { return "<li>" + esc(b) + "</li>"; }).join("") + "</ul>" +
      '<div class="fee"><b>Maliyet:</b> ' + esc(p.costs.fee) + "</div>" +
      '<div class="tags">' + p.perks.map(function (k) { return '<span class="tag">' + esc(META.perks[k]) + "</span>"; }).join("") + "</div>" +
      '<div class="actions"><label class="cmp-toggle"><input type="checkbox" data-cmp="' + p.id + '"' + checked + "> Karşılaştır</label>" +
      '<span class="conf ' + p.confidence + '" title="' + esc(META.confidence[p.confidence]) + '">' + (p.confidence === "dogrulandi" ? "✓ resmi kaynak" : p.confidence === "ikincil" ? "◐ ikincil kaynak" : "⚠ doğrulayın") + "</span></div>" +
      "</article>";
  }
  function bindCmp(root) {
    root.addEventListener("change", function (e) {
      var id = e.target.getAttribute && e.target.getAttribute("data-cmp");
      if (!id) return;
      if (!toggleCmp(id, e.target.checked)) e.target.checked = false;
    });
  }

  /* ---------- index / list page ---------- */
  function initList() {
    var params = new URLSearchParams(location.search);
    var state = {
      q: params.get("q") || "",
      cat: params.get("kategori") || "",
      perks: (params.get("avantaj") || "").split(",").filter(Boolean),
      fee: params.get("aidat") || "",
      status: params.get("durum") || "aktif",
      sort: params.get("sirala") || "kategori",
    };
    var q = $("#f-q"), catSel = $("#f-cat"), feeSel = $("#f-fee"), stSel = $("#f-status"), sortSel = $("#f-sort"), chips = $("#f-perks");

    catSel.innerHTML = '<option value="">Tüm kategoriler</option>' + Object.keys(META.categories).map(function (k) {
      return '<option value="' + k + '">' + esc(META.categories[k].label) + "</option>";
    }).join("");
    chips.innerHTML = Object.keys(META.perks).map(function (k) {
      return '<button type="button" class="chip" data-perk="' + k + '" aria-pressed="false">' + esc(META.perks[k]) + "</button>";
    }).join("");

    q.value = state.q; catSel.value = state.cat; feeSel.value = state.fee; stSel.value = state.status; sortSel.value = state.sort;

    function sync() {
      chips.querySelectorAll(".chip").forEach(function (c) { c.setAttribute("aria-pressed", state.perks.indexOf(c.getAttribute("data-perk")) >= 0); });
      var qs = new URLSearchParams();
      if (state.q) qs.set("q", state.q);
      if (state.cat) qs.set("kategori", state.cat);
      if (state.perks.length) qs.set("avantaj", state.perks.join(","));
      if (state.fee) qs.set("aidat", state.fee);
      if (state.status !== "aktif") qs.set("durum", state.status);
      if (state.sort !== "kategori") qs.set("sirala", state.sort);
      var s = qs.toString();
      history.replaceState(null, "", location.pathname + (s ? "?" + s : ""));
      render();
    }

    function render() {
      var nq = norm(state.q);
      var list = PRODUCTS.filter(function (p) {
        if (state.cat && p.category !== state.cat) return false;
        if (state.status === "aktif" && p.status !== "aktif") return false;
        if (state.fee === "free" && !isFree(p)) return false;
        if (state.fee === "paid" && isFree(p)) return false;
        for (var i = 0; i < state.perks.length; i++) if (p.perks.indexOf(state.perks[i]) < 0) return false;
        if (nq) {
          var hay = norm([p.name, p.provider, p.program, p.subcategory, p.summary, p.benefits.join(" ")].join(" "));
          if (nq.split(/\s+/).some(function (w) { return hay.indexOf(w) < 0; })) return false;
        }
        return true;
      });
      var order = Object.keys(META.categories);
      list.sort(function (a, b) {
        if (state.sort === "kampanya") return activeCampaigns(b).length - activeCampaigns(a).length || a.name.localeCompare(b.name, "tr");
        if (state.sort === "ad") return a.name.localeCompare(b.name, "tr");
        return order.indexOf(a.category) - order.indexOf(b.category) || a.name.localeCompare(b.name, "tr");
      });
      $("#count").textContent = list.length + " sonuç";
      $("#grid").innerHTML = list.length ? list.map(card).join("") : '<p class="empty">Bu filtrelere uyan ürün yok.</p>';
    }

    q.addEventListener("input", function () { state.q = q.value.trim(); sync(); });
    catSel.addEventListener("change", function () { state.cat = catSel.value; sync(); });
    feeSel.addEventListener("change", function () { state.fee = feeSel.value; sync(); });
    stSel.addEventListener("change", function () { state.status = stSel.value; sync(); });
    sortSel.addEventListener("change", function () { state.sort = sortSel.value; sync(); });
    chips.addEventListener("click", function (e) {
      var k = e.target.getAttribute("data-perk");
      if (!k) return;
      var i = state.perks.indexOf(k);
      if (i >= 0) state.perks.splice(i, 1); else state.perks.push(k);
      sync();
    });
    $("#f-reset").addEventListener("click", function () {
      state = { q: "", cat: "", perks: [], fee: "", status: "aktif", sort: "kategori" };
      q.value = ""; catSel.value = ""; feeSel.value = ""; stSel.value = "aktif"; sortSel.value = "kategori";
      sync();
    });

    // category tiles
    var tiles = $("#cat-tiles");
    if (tiles) {
      tiles.innerHTML = Object.keys(META.categories).map(function (k) {
        var c = META.categories[k];
        var n = PRODUCTS.filter(function (p) { return p.category === k; }).length;
        return '<a class="cat-tile" href="?kategori=' + k + '#liste"><span class="count">' + n + '</span><span class="ico">' + c.icon + "</span><h3>" + esc(c.label) + "</h3><p>" + esc(c.desc) + "</p></a>";
      }).join("");
      tiles.addEventListener("click", function (e) {
        var a = e.target.closest("a.cat-tile");
        if (!a) return;
        e.preventDefault();
        state.cat = new URLSearchParams(a.getAttribute("href").split("#")[0]).get("kategori");
        catSel.value = state.cat;
        sync();
        $("#liste").scrollIntoView({ behavior: "smooth" });
      });
    }
    var stats = $("#stats");
    if (stats) {
      var allCamps = PRODUCTS.reduce(function (n, p) { return n + activeCampaigns(p).length; }, 0);
      var free = PRODUCTS.filter(function (p) { return p.category === "kredi-karti" && p.perks.indexOf("aidatsiz") >= 0; }).length;
      stats.innerHTML = [
        [PRODUCTS.length, "ürün ve program"],
        [Object.keys(META.categories).length, "kategori"],
        [allCamps, "aktif kampanya"],
        [free, "aidatsız kart"],
      ].map(function (s) { return '<div class="stat"><b>' + s[0] + "</b><span>" + s[1] + "</span></div>"; }).join("");
    }

    bindCmp($("#grid"));
    sync();
  }

  /* ---------- perks page ---------- */
  function initPerks() {
    var root = $("#perk-sections");
    var keys = Object.keys(META.perks);
    $("#perk-nav").innerHTML = keys.map(function (k) {
      var n = PRODUCTS.filter(function (p) { return p.status === "aktif" && p.perks.indexOf(k) >= 0; }).length;
      return '<a class="chip" href="#' + k + '">' + esc(META.perks[k]) + " (" + n + ")</a>";
    }).join("");
    root.innerHTML = keys.map(function (k) {
      var list = PRODUCTS.filter(function (p) { return p.status === "aktif" && p.perks.indexOf(k) >= 0; });
      var order = Object.keys(META.categories);
      list.sort(function (a, b) { return order.indexOf(a.category) - order.indexOf(b.category) || a.name.localeCompare(b.name, "tr"); });
      return '<section id="' + k + '"><h2 class="section-title">' + esc(META.perks[k]) + '</h2><p class="section-sub">' + list.length +
        ' ürün · <a href="index.html?avantaj=' + k + '#liste">listede filtrele</a></p><div class="grid">' + list.map(card).join("") + "</div></section>";
    }).join("");
    bindCmp(root);
  }

  /* ---------- compare page ---------- */
  function initCompare() {
    var ids = (new URLSearchParams(location.search).get("ids") || "").split(",").filter(byId);
    if (!ids.length) ids = getCmp();
    var list = ids.map(byId).slice(0, MAX_COMPARE);
    var out = $("#compare");
    var picker = $("#cmp-add");
    picker.innerHTML = '<option value="">+ Ürün ekle…</option>' + Object.keys(META.categories).map(function (k) {
      return '<optgroup label="' + esc(META.categories[k].label) + '">' + PRODUCTS.filter(function (p) { return p.category === k; })
        .map(function (p) { return '<option value="' + p.id + '">' + esc(p.name) + " – " + esc(p.provider) + "</option>"; }).join("") + "</optgroup>";
    }).join("");
    picker.addEventListener("change", function () {
      if (!picker.value) return;
      var next = list.map(function (p) { return p.id; }).filter(function (x) { return x !== picker.value; });
      if (next.length >= MAX_COMPARE) { alert("En fazla " + MAX_COMPARE + " ürün."); picker.value = ""; return; }
      next.push(picker.value);
      setCmp(next);
      location.search = "?ids=" + next.join(",");
    });
    if (list.length === 0) {
      out.innerHTML = '<p class="empty">Karşılaştırmak için listeden ürün seçin veya yukarıdan ekleyin.</p>';
      return;
    }
    function ul(arr) { return arr && arr.length ? "<ul>" + arr.map(function (x) { return "<li>" + esc(x) + "</li>"; }).join("") + "</ul>" : "—"; }
    var rows = [
      ["Kategori", function (p) { return esc(META.categories[p.category].label) + "<br><small>" + esc(p.subcategory) + "</small>"; }],
      ["Sağlayıcı", function (p) { return esc(p.provider); }],
      ["Program", function (p) { return esc(p.program); }],
      ["Durum", function (p) { return esc(META.status[p.status]); }],
      ["Özet", function (p) { return esc(p.summary); }],
      ["Avantajlar", function (p) { return ul(p.benefits); }],
      ["Avantaj türleri", function (p) { return p.perks.map(function (k) { return '<span class="tag">' + esc(META.perks[k]) + "</span>"; }).join(" "); }],
      ["Yıllık ücret / maliyet", function (p) { return "<b>" + esc(p.costs.fee) + "</b>"; }],
      ["Koşullar", function (p) { return ul(p.costs.conditions); }],
      ["Puan geçerliliği", function (p) { return esc(p.costs.expiry || "—"); }],
      ["Aktif kampanyalar", function (p) { var c = activeCampaigns(p); return c.length ? ul(c.map(function (x) { return x.title + (x.until ? " (" + fmtDate(x.until) + "'e kadar)" : ""); })) : "—"; }],
      ["Güvenilirlik", function (p) { return esc(META.confidence[p.confidence]); }],
      ["", function (p) { return '<a href="' + url(p) + '">Detay →</a> · <a href="#" data-remove="' + p.id + '">Çıkar</a>'; }],
    ];
    out.innerHTML = '<div class="table-wrap"><table class="cmp-table"><thead><tr><th></th>' +
      list.map(function (p) { return "<th>" + esc(p.name) + "</th>"; }).join("") + "</tr></thead><tbody>" +
      rows.map(function (r) { return "<tr><td>" + r[0] + "</td>" + list.map(function (p) { return "<td>" + r[1](p) + "</td>"; }).join("") + "</tr>"; }).join("") +
      "</tbody></table></div>";
    out.addEventListener("click", function (e) {
      var id = e.target.getAttribute("data-remove");
      if (!id) return;
      e.preventDefault();
      var next = list.map(function (p) { return p.id; }).filter(function (x) { return x !== id; });
      setCmp(next);
      location.search = next.length ? "?ids=" + next.join(",") : "";
    });
  }

  /* ---------- campaigns page ---------- */
  function initCampaigns() {
    var rows = [];
    PRODUCTS.forEach(function (p) { (p.campaigns || []).forEach(function (c) { rows.push({ p: p, c: c }); }); });
    rows.sort(function (a, b) { return (a.c.until || "9999") < (b.c.until || "9999") ? -1 : 1; });
    var showExpired = $("#show-expired");
    function render() {
      var list = rows.filter(function (r) { return showExpired.checked || !r.c.until || r.c.until >= TODAY; });
      $("#camp-count").textContent = list.length + " kampanya";
      $("#campaigns").innerHTML = list.length ? '<div class="table-wrap"><table><thead><tr><th>Bitiş</th><th>Kampanya</th><th>Ürün</th><th>Kaynak</th></tr></thead><tbody>' +
        list.map(function (r) {
          var expired = r.c.until && r.c.until < TODAY;
          return "<tr" + (expired ? ' style="opacity:.55"' : "") + "><td>" + (r.c.until ? fmtDate(r.c.until) : "Süresiz / belirtilmemiş") + (expired ? "<br><small>sona erdi</small>" : "") + "</td><td>" + esc(r.c.title) +
            (r.c.note ? "<br><small>" + esc(r.c.note) + "</small>" : "") + '</td><td><a href="' + url(r.p) + '">' + esc(r.p.name) + "</a><br><small>" + esc(r.p.provider) +
            '</small></td><td><a href="' + esc(r.c.source.url) + '" target="_blank" rel="noopener">' + esc(r.c.source.label) + "</a></td></tr>";
        }).join("") + "</tbody></table></div>" : '<p class="empty">Aktif kampanya yok.</p>';
    }
    showExpired.addEventListener("change", render);
    render();
  }

  /* ---------- product detail page: campaign expiry + compare button ---------- */
  function initDetail() {
    document.querySelectorAll(".camp[data-until]").forEach(function (el) {
      if (el.getAttribute("data-until") < TODAY) {
        el.classList.add("expired");
        el.querySelector("small").textContent += " · sona erdi";
      }
    });
    var btn = $("#cmp-btn");
    if (btn) {
      var id = btn.getAttribute("data-id");
      function label() { btn.textContent = getCmp().indexOf(id) >= 0 ? "Karşılaştırmadan çıkar" : "Karşılaştırmaya ekle"; }
      btn.addEventListener("click", function () { toggleCmp(id, getCmp().indexOf(id) < 0); label(); });
      label();
    }
  }

  /* ---------- theme toggle ---------- */
  function initTheme() {
    var btn = $("#theme-btn");
    try { var t = localStorage.getItem("perks-theme"); if (t) document.documentElement.setAttribute("data-theme", t); } catch (e) { /* ignore */ }
    if (!btn) return;
    btn.addEventListener("click", function () {
      var cur = document.documentElement.getAttribute("data-theme") ||
        (window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light");
      var next = cur === "dark" ? "light" : "dark";
      document.documentElement.setAttribute("data-theme", next);
      try { localStorage.setItem("perks-theme", next); } catch (e) { /* ignore */ }
    });
  }

  initTheme();
  var page = document.body.getAttribute("data-page");
  if (page === "list") initList();
  else if (page === "perks") initPerks();
  else if (page === "compare") initCompare();
  else if (page === "campaigns") initCampaigns();
  else if (page === "detail") initDetail();
  renderTray();
})();
